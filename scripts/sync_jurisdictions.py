#!/usr/bin/env python3
"""sync_jurisdictions.py — generate jurisdictions.py from terms-analysis schemas.py.

Reads the Jurisdiction Literal from terms-analysis::schemas.py via AST parsing
and writes src/legal_corpus_ingester/jurisdictions.py with a frozenset.

Run: python scripts/sync_jurisdictions.py
Idempotent: running twice produces identical output.
"""
from __future__ import annotations
import ast
import sys
from pathlib import Path

TERMS_ANALYSIS_SCHEMAS = Path(__file__).parent.parent.parent / "terms-analysis" / "src" / "backend" / "app" / "schemas.py"
OUT_FILE = Path(__file__).parent.parent / "src" / "legal_corpus_ingester" / "jurisdictions.py"

HEADER = '''\
# AUTO-GENERATED by scripts/sync_jurisdictions.py — do not edit manually.
# Source: terms-analysis/src/backend/app/schemas.py Jurisdiction Literal
# Run `python scripts/sync_jurisdictions.py` to regenerate.
from __future__ import annotations

JURISDICTION_CODES: frozenset[str] = frozenset({{
{entries}
}})
'''


def _extract_literal_strings(slice_node: ast.expr) -> list[str]:
    """Extract string constants from a Literal slice (Tuple or single Constant)."""
    codes: list[str] = []
    if isinstance(slice_node, ast.Tuple):
        for elt in slice_node.elts:
            if isinstance(elt, ast.Constant) and isinstance(elt.value, str):
                codes.append(elt.value)
    elif isinstance(slice_node, ast.Constant) and isinstance(slice_node.value, str):
        codes.append(slice_node.value)
    return codes


def extract_jurisdiction_codes(schemas_path: Path) -> list[str]:
    """Parse schemas.py AST to extract Jurisdiction Literal string arguments.

    Handles both:
    - ``Jurisdiction = Literal[...]``  (ast.Assign)
    - ``Jurisdiction: TypeAlias = Literal[...]``  (ast.AnnAssign)
    """
    source = schemas_path.read_text(encoding="utf-8")
    tree = ast.parse(source, filename=str(schemas_path))
    for node in ast.walk(tree):
        # Handle: Jurisdiction = Literal[...]
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id == "Jurisdiction":
                    if isinstance(node.value, ast.Subscript):
                        codes = _extract_literal_strings(node.value.slice)
                        if codes:
                            return codes
        # Handle: Jurisdiction: TypeAlias = Literal[...]
        if isinstance(node, ast.AnnAssign):
            target = node.target
            if isinstance(target, ast.Name) and target.id == "Jurisdiction":
                ann = node.annotation
                if isinstance(ann, ast.Subscript):
                    codes = _extract_literal_strings(ann.slice)
                    if codes:
                        return codes
    raise ValueError(f"Could not find 'Jurisdiction' Literal assignment in {schemas_path}")


def main() -> None:
    if not TERMS_ANALYSIS_SCHEMAS.exists():
        print(f"ERROR: terms-analysis schemas not found at {TERMS_ANALYSIS_SCHEMAS}", file=sys.stderr)
        sys.exit(1)

    codes = sorted(extract_jurisdiction_codes(TERMS_ANALYSIS_SCHEMAS))
    entries = "\n".join(f'    "{code}",' for code in codes)
    content = HEADER.format(entries=entries)
    OUT_FILE.write_text(content, encoding="utf-8")
    print(f"Written {len(codes)} jurisdiction codes to {OUT_FILE}")


if __name__ == "__main__":
    main()
